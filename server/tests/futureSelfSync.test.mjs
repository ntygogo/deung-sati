assert.equal(damaged.commit(emptyFutureJournal()), false); assert.equal(corrupt.getItem('deung_sati_future_practice_v1_a'), '{broken');
const full = new FutureSelfStore('guest', {getItem:()=>null,setItem:()=>{throw new Error('full')}});
assert.equal(full.commit({focus:focus(),entries:[]}), false);
assert.deepEqual(await db.query('SELECT * FROM ledger'), [{points:15}], 'Future Self never grants loop rewards');
